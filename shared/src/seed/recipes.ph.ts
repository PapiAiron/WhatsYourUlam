import type {
  AllergenId,
  DietFlag,
  EquipmentRequirement,
  MealType,
  NutritionInfo,
  Recipe,
  RecipeIngredient,
} from '../types/index.ts';
import { INGREDIENT_MAP } from './ingredients.ts';

interface RawRecipeSpec {
  id: string;
  name: string;
  localName: string;
  description: string;
  mealTypes: MealType[];
  proteinTags: string[];
  equipmentRequired: EquipmentRequirement[];
  prepMin: number;
  cookMin: number;
  difficulty: 'easy' | 'medium';
  ingredients: RecipeIngredient[];
  steps: string[];
  tips: string;
  imageUrl?: string;
  accentTone?: 'clay' | 'moss' | 'turmeric' | 'tamarind';
}

function deriveRecipeMetadata(
  ingredients: RecipeIngredient[],
  proteinTags: string[]
): {
  allergens: AllergenId[];
  dietFlags: DietFlag[];
  nutritionPerServing: NutritionInfo;
} {
  const allergenSet = new Set<AllergenId>();
  let totalKcal = 0;
  let totalProtein = 0;
  let totalCarbs = 0;
  let totalFat = 0;

  for (const item of ingredients) {
    const ing = INGREDIENT_MAP.get(item.ingredientId);
    if (!ing) continue;
    for (const a of ing.allergens) {
      allergenSet.add(a);
    }
    const gramsOrMl =
      ing.canonicalUnit === 'pc'
        ? item.qty * (ing.gramsPerPiece ?? 50)
        : item.qty;
    const factor = gramsOrMl / 100;
    totalKcal += ing.nutritionPer100.kcal * factor;
    totalProtein += ing.nutritionPer100.proteinG * factor;
    totalCarbs += ing.nutritionPer100.carbsG * factor;
    totalFat += ing.nutritionPer100.fatG * factor;
  }

  const hasPork = proteinTags.includes('pork');
  const hasMeat =
    proteinTags.includes('pork') ||
    proteinTags.includes('chicken') ||
    proteinTags.includes('beef');
  const hasFishOrSeafood =
    proteinTags.includes('fish') || proteinTags.includes('seafood');

  const dietFlags: DietFlag[] = ['none'];
  if (!hasPork) {
    dietFlags.push('no_pork');
    dietFlags.push('halal');
  }
  if (!hasMeat) {
    dietFlags.push('pescatarian');
  }
  if (!hasMeat && !hasFishOrSeafood) {
    dietFlags.push('vegetarian');
  }

  return {
    allergens: Array.from(allergenSet),
    dietFlags,
    nutritionPerServing: {
      kcal: Math.round(totalKcal / 4),
      proteinG: Math.round(totalProtein / 4),
      carbsG: Math.round(totalCarbs / 4),
      fatG: Math.round(totalFat / 4),
    },
  };
}

function buildRecipe(spec: RawRecipeSpec): Recipe {
  const derived = deriveRecipeMetadata(spec.ingredients, spec.proteinTags);
  return {
    id: spec.id,
    slug: spec.id,
    name: spec.name,
    localName: spec.localName,
    description: spec.description,
    country: 'PH',
    cuisineTags: ['filipino', 'home-cooked'],
    mealTypes: spec.mealTypes,
    proteinTags: spec.proteinTags,
    equipmentRequired: spec.equipmentRequired,
    allergens: derived.allergens,
    dietFlags: derived.dietFlags,
    baseServings: 4,
    prepMin: spec.prepMin,
    cookMin: spec.cookMin,
    difficulty: spec.difficulty,
    ingredients: spec.ingredients,
    steps: spec.steps,
    tips: spec.tips,
    nutritionPerServing: derived.nutritionPerServing,
    image: spec.imageUrl
      ? {
          status: 'ready',
          url: spec.imageUrl,
          thumbUrl: spec.imageUrl,
          w: 1200,
          h: 900,
          promptVersion: 'v1',
        }
      : {
          status: 'ready',
          promptVersion: 'svg-fallback',
        },
    status: 'approved',
    source: 'seed',
    qualityScore: 95,
    version: 1,
    accentTone: spec.accentTone ?? 'clay',
  };
}

